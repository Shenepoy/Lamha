// TextSize is the rendered cap height for the text tool.
func TextSize(width float64) float64 {
	return math.Max(18, width*3.1)
}

func drawLabel(dst *image.NRGBA, x, y float64, text string, ink color.NRGBA, width float64) {
	if drawPangoLabel(dst, x, y, text, ink, width) {
		return
	}
	cell := math.Max(2.2, TextSize(width)/7)
	gap := cell * 0.28
	radius := cell * 0.58
	cx := x
	cy := y
	for _, r := range text {
		if r == '\n' {
			cx = x
			cy += 8 * cell
			continue
		}
		drawASCIIGlyph(dst, cx, cy, r, cell, radius, ink)
		cx += 6*cell + gap
	}
}

func textBounds(x, y float64, text string, width float64) image.Rectangle {
	if bounds, ok := pangoTextBounds(x, y, text, width); ok {
		return bounds
	}
	if text == "" {
		cell := math.Max(2.2, TextSize(width)/7)
		return RectFromPoints(x, y, x+6*cell, y+7*cell)
	}
	cell := math.Max(2.2, TextSize(width)/7)
	gap := cell * 0.28
	lines := 1
	maxCols := 0
	cols := 0
	for _, r := range text {
		if r == '\n' {
			if cols > maxCols {
				maxCols = cols
			}
			cols = 0
			lines++
			continue
		}
		cols++
	}
	if cols > maxCols {
		maxCols = cols
	}
	if maxCols < 1 {
		maxCols = 1
	}
	w := float64(maxCols)*(6*cell+gap) - gap
	h := float64(lines)*8*cell - cell
	return RectFromPoints(x-cell, y-cell, x+w+cell, y+h+cell)
}

func hitText(s Stroke, p Point, slop float64) bool {
	r := textBounds(s.X1, s.Y1, s.Text, s.Width).Inset(-int(math.Ceil(slop)))
	return image.Pt(int(math.Round(p.X)), int(math.Round(p.Y))).In(r)
}

func drawASCIIGlyph(dst *image.NRGBA, x0, y0 float64, r rune, cell, radius float64, ink color.NRGBA) {
	rows := glyph5x7(r)
	for row, bits := range rows {
		for col := 0; col < 5; col++ {
			if bits&(1<<uint(4-col)) == 0 {
				continue
			}
			stampDisc(dst, x0+(float64(col)+0.5)*cell, y0+(float64(row)+0.5)*cell, radius, ink)
		}
	}
}

func glyph5x7(r rune) [7]byte {
	if r > unicode.MaxASCII {
		r = '?'
	}
	if r < 32 || r > 126 {
		r = '?'
	}
	return ascii5x7[r-32]
}

